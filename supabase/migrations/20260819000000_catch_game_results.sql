-- Store one immutable result per completed CatchCare round.

create table if not exists public.catch_game_results (
  id bigint generated by default as identity primary key,
  phone text not null,
  last_name text not null default '',
  tg_user_id bigint,
  bag_type text not null,
  score integer not null default 0,
  caught_products jsonb not null default '{}'::jsonb,
  duration_seconds numeric(7, 2) not null default 0,
  ended_reason text not null default 'hazard',
  created_at timestamptz not null default now(),
  constraint catch_game_results_bag_type_check check (bag_type in ('black', 'purple')),
  constraint catch_game_results_score_check check (score >= 0),
  constraint catch_game_results_duration_check check (duration_seconds >= 0 and duration_seconds <= 600),
  constraint catch_game_results_ended_reason_check check (ended_reason in ('hazard', 'time'))
);

create index if not exists catch_game_results_created_at_idx
  on public.catch_game_results (created_at desc);

create index if not exists catch_game_results_phone_idx
  on public.catch_game_results (phone, created_at desc);

alter table public.catch_game_results enable row level security;

drop policy if exists "CatchCare results can be created from app" on public.catch_game_results;

-- The game can append results but cannot read the analytics table through the
-- public client. Read access remains available to Supabase dashboard/service role.
create policy "CatchCare results can be created from app"
on public.catch_game_results
for insert
to anon, authenticated
with check (
  bag_type in ('black', 'purple')
  and score >= 0
  and duration_seconds between 0 and 600
);
